-- ============================================================================
--  Reports and share tokens.
--
--  These are the queries behind queries.go. They are the *same statements* the
--  SQLite implementation ran, translated rather than redesigned, because P2's
--  contract is that behaviour does not change: the 14 frozen contracts and the
--  ~250 existing test functions are the specification, and a query that looks
--  nicer but answers differently is a regression with a compile-time alibi.
--
--  Three translations carry the whole risk of this file:
--
--  1. SQLite's two-argument max(a, b) is GREATEST(a, b) in PostgreSQL. `max()`
--     here is an aggregate, so the naive translation is a query that either
--     fails or silently aggregates.
--  2. The two partial-update statements were built by concatenating a SET list
--     in Go. That cannot be generated by sqlc, and it is also where "field
--     absent" vs "field set to this value" is decided. COALESCE(narg, column)
--     expresses the same thing as one static statement: NULL means "absent",
--     and any non-NULL value — including '' and 0 — is written through.
--  3. `updated_at = GREATEST(@now_ms, updated_at + 1)` must keep the +1. It is
--     not cosmetic: it guarantees the column always changes, which is the
--     condition trg_reports_touch_updated_at watches for. If the trigger
--     fires it re-stamps the column from the database clock, and the invariant
--     "updated_at is strictly increasing and never before created_at" would
--     then depend on that clock instead of on this statement.
-- ============================================================================

-- name: CreateReport :exec
INSERT INTO reports (id, title, category, format, content, metadata,
                     created_at, updated_at, owner_key_id)
VALUES (@id, @title, @category, @format, @content, @metadata,
        @created_at, @updated_at, @owner_key_id);

-- name: GetReport :one
SELECT id, title, category, format, content, metadata, created_at, updated_at, owner_key_id
FROM reports
WHERE id = @id;

-- name: ListReports :many
-- @category = '' means "every category". The API layer only ever passes a real
-- category or the empty string, and category is NOT NULL DEFAULT 'general', so
-- the two branches cannot disagree about a row.
SELECT id, title, category, format, ''::text AS content, metadata,
       created_at, updated_at, owner_key_id
FROM reports
WHERE (@category::text = '' OR category = @category)
ORDER BY created_at DESC
LIMIT @limit_count OFFSET @offset_count;

-- name: ListReportsByOwner :many
-- owner_key_id = '' is a real value, not a wildcard: it selects the reports the
-- root credential published. Callers wanting everything use ListReports.
SELECT id, title, category, format, ''::text AS content, metadata,
       created_at, updated_at, owner_key_id
FROM reports
WHERE owner_key_id = @owner_key_id
  AND (@category::text = '' OR category = @category)
ORDER BY created_at DESC
LIMIT @limit_count OFFSET @offset_count;

-- name: ReportExists :one
SELECT EXISTS (SELECT 1 FROM reports WHERE id = @id);

-- name: ReportOwner :one
SELECT owner_key_id FROM reports WHERE id = @id;

-- name: UpdateReport :execrows
-- A nil argument leaves its column untouched; see the file header. `format` is
-- passed as a string and the CHECK constraint still rejects anything else.
UPDATE reports
SET title      = COALESCE(sqlc.narg('title')::text, title),
    category   = COALESCE(sqlc.narg('category')::text, category),
    format     = COALESCE(sqlc.narg('format')::text, format),
    content    = COALESCE(sqlc.narg('content')::text, content),
    metadata   = COALESCE(sqlc.narg('metadata')::text, metadata),
    updated_at = GREATEST(@now_ms::bigint, updated_at + 1)
WHERE id = sqlc.arg('id');

-- name: DeleteReport :execrows
DELETE FROM reports WHERE id = @id;

-- ----------------------------------------------------------------------------
--  share_tokens
-- ----------------------------------------------------------------------------

-- name: CreateShareToken :exec
INSERT INTO share_tokens (token, report_id, created_at, expires_at, is_active, view_count)
VALUES (@token, @report_id, @created_at, @expires_at, 1, 0);

-- name: GetShareToken :one
SELECT token, report_id, created_at, expires_at, is_active, view_count
FROM share_tokens
WHERE token = @token;

-- name: ListShareTokens :many
SELECT token, report_id, created_at, expires_at, is_active, view_count
FROM share_tokens
WHERE report_id = @report_id
ORDER BY created_at DESC;

-- name: ShareTokenExists :one
SELECT EXISTS (SELECT 1 FROM share_tokens WHERE token = @token);

-- name: RevokeShareToken :execrows
-- The `is_active = 1` predicate is what makes revoking an already-revoked token
-- a no-op rather than a second state change; the caller distinguishes "already
-- revoked" from "never existed" with ShareTokenExists, not with this count.
UPDATE share_tokens SET is_active = 0
WHERE token = @token AND is_active = 1;

-- name: UpdateShareToken :execrows
-- Both columns are optional and independent, so there are four legal patches.
-- sqlc.narg keeps them nullable: a NULL means "leave this column alone".
UPDATE share_tokens
SET expires_at = COALESCE(sqlc.narg('expires_at')::bigint, expires_at),
    is_active  = COALESCE(sqlc.narg('is_active')::integer, is_active)
WHERE token = sqlc.arg('token');

-- name: DeleteShareToken :execrows
DELETE FROM share_tokens WHERE token = @token;

-- name: RecordShareView :exec
-- A single atomic increment: the read-modify-write that would need locking in
-- Go cannot happen here. Best-effort by design — a failure must never fail the
-- page render.
UPDATE share_tokens SET view_count = view_count + 1 WHERE token = @token;

-- name: CleanupExpiredShareTokens :execrows
-- Both conditions are required: a revoked token whose expires_at is 0 carries no
-- information that would justify deleting the row.
DELETE FROM share_tokens
WHERE is_active = 0 AND expires_at != 0 AND expires_at < @now_ms;

-- name: ResolveShare :one
-- Liveness is computed by the caller from expires_at, so this statement reads
-- the row whatever its state: "unknown" and "revoked" must both come back as
-- data, because the store answers Missing for both while "expired" is Gone.
SELECT
  t.token,
  t.report_id,
  t.created_at        AS token_created_at,
  t.expires_at        AS token_expires_at,
  t.is_active         AS token_is_active,
  t.view_count        AS token_view_count,
  r.id                AS report_id_of_report,
  r.title             AS report_title,
  r.category          AS report_category,
  r.format            AS report_format,
  r.content           AS report_content,
  r.metadata          AS report_metadata,
  r.created_at        AS report_created_at,
  r.updated_at        AS report_updated_at
FROM share_tokens t
JOIN reports r ON r.id = t.report_id
WHERE t.token = @token;

-- name: ShareTokenOwner :one
SELECT r.owner_key_id, t.is_active
FROM share_tokens t
JOIN reports r ON r.id = t.report_id
WHERE t.token = @token;
